interface InteractiveCompileOptions {
  document: vscode.TextDocument;
  defaultGame: GameProfile;
  supportedGames: GameProfile[];
  getSettingsForGame: (game: GameProfile) => CompilerSettingsSnapshot;
  includeFlag: string;
  pathSeparator: string;
}

interface CompilerFlagDefinition {
  id: string;
  flag: string;
  label: string;
  description: string;
  detail?: string;
  requiresValue?: boolean;
  valueType?: 'string' | 'folder' | 'folders' | 'file' | 'saveFile';
  valuePrompt?: string;
  valuePlaceholder?: string;
  allowedGames?: GameProfile[];
  incompatibleWith?: string[];
  allowDuplicates?: boolean;
  formatValue?: (value: string, separators: { path: string }) => string;
  valueValidation?: (value: string) => string | undefined;
  iconId?: string;
}

interface SelectedFlag {
  id: string;
  rendered: string;
  definition: CompilerFlagDefinition | null;
  value?: string;
  source: 'existing' | 'user';
}

interface GamePickItem extends vscode.QuickPickItem {
  game: GameProfile;
}

interface ExistingArgumentsChoice extends vscode.QuickPickItem {
  value: 'keep' | 'discard';
}

interface RemovalPickItem extends vscode.QuickPickItem {
  flag: SelectedFlag;
}

interface ScriptPathPickItem extends vscode.QuickPickItem {
  action: 'done' | 'add' | 'restore' | 'remove';
  target?: string;
}

interface WorkingDirectoryPickItem extends vscode.QuickPickItem {
  action: 'use-current' | 'compiler' | 'script' | 'browse' | 'none';
}

interface FlagPickerItem extends vscode.QuickPickItem {
  action: 'definition' | 'custom' | 'remove' | 'finish';
  definition?: CompilerFlagDefinition;
}

interface CompilerPathPickItem extends vscode.QuickPickItem {
  action: 'use' | 'browse' | 'manual';
}

